"""Generate immutable Java values and client vocabulary from the canonical JSON contracts."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'backend/src/main/resources/assistant-contract.json'
target=ROOT/'miniprogram/utils/assistant-contract.js'
spec=json.loads(source.read_text(encoding='utf-8'))
CLIENT_KEYS=(
    'version','maxQueries','maxClarifications','requiredFields','intents','intentLabels',
    'times','timeLabels','categories','categoryLabels','states','stateLabels',
    'timeOptionsByIntent','timeLabelsByIntent','entryCommands',
)
client_spec={key:spec[key] for key in CLIENT_KEYS}
content='// Generated by scripts/sync-assistant-contract.py; edit the server contract, not this file.\nmodule.exports = '+json.dumps(client_spec,ensure_ascii=False,indent=2)+'\n'
def java_value(value):
    if isinstance(value, dict):
        entries = [json.dumps(k, ensure_ascii=False) + ', ' + java_value(v) for k, v in value.items()]
        return 'object(' + ', '.join(entries) + ')'
    if isinstance(value, list):
        return 'Collections.unmodifiableList(Arrays.asList(' + ', '.join(map(java_value, value)) + '))'
    return json.dumps(value, ensure_ascii=False)


def java_source():
    protocol = json.loads((source.parent / 'assistant-locator-protocol.json').read_text(encoding='utf-8'))
    return ("package cn.qingye.model;\n\nimport java.util.*;\n\n"
        "// Generated by scripts/sync-assistant-contract.py from the two JSON contracts.\n"
        "// Immutable values only: no resource IO, JSON parser or execution dependency.\n"
        "final class AssistantContractData {\n"
        "    static final Map<String,Object> BUSINESS = " + java_value(spec) + ";\n"
        "    static final Map<String,Object> LOCATOR = " + java_value(protocol) + ";\n"
        "    private static Map<String,Object> object(Object... entries) {\n"
        "        var result = new LinkedHashMap<String,Object>();\n"
        "        for (int i=0;i<entries.length;i+=2) result.put((String)entries[i],entries[i+1]);\n"
        "        return Collections.unmodifiableMap(result);\n"
        "    }\n"
        "    private AssistantContractData() {}\n"
        "}\n")

parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
outputs = {target: content, ROOT/'backend/src/main/java/cn/qingye/model/AssistantContractData.java': java_source()}
for path, expected in outputs.items():
    if args.check:
        if not path.exists() or path.read_text(encoding='utf-8') != expected:
            raise SystemExit('Assistant contract output is stale: '+str(path.relative_to(ROOT))+'; run scripts/sync-assistant-contract.py')
    else:
        path.write_text(expected,encoding='utf-8',newline='\n')
        print('Generated '+str(path.relative_to(ROOT)))
if args.check: print('Assistant capability vocabulary and immutable Java data: PASS')
