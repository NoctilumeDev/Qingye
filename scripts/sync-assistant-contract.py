"""Generate the mini-program vocabulary from the same capability file used by Java and prompts."""
import argparse
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'backend/src/main/resources/assistant-contract.json'
target=ROOT/'miniprogram/utils/assistant-contract.js'
spec=json.loads(source.read_text(encoding='utf-8'))
content='// Generated by scripts/sync-assistant-contract.py; edit the server contract, not this file.\nmodule.exports = '+json.dumps(spec,ensure_ascii=False,indent=2)+'\n'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:
    if not target.exists() or target.read_text(encoding='utf-8')!=content:raise SystemExit('Assistant capability vocabulary is stale; run scripts/sync-assistant-contract.py')
    print('Assistant capability vocabulary: PASS')
else:
    target.write_text(content,encoding='utf-8');print('Generated '+str(target))
